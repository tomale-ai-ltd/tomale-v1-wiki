"""Build golden-set-v1.json from Kyle's Xano exports (26/11/2026) plus three authored stories.

Inputs only: frozen story inputs (style, theme, prompt, synopsis, page text, character JSON).
Baselines are regenerated by the eval harness; existing images are not used. Existing
character pictures are not used either: portraits are regenerated from the JSON, because
test-account characters may be modelled on real family members.
"""
