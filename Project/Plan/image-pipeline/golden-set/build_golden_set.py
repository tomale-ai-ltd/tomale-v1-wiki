R = lambda f: list(csv.DictReader(open(U / f, newline="", encoding="utf-8")))
stories = {x["id"]: x for x in R("b9398617-instant_stories-export.2026-11-26T16_16_08.82300_00.csv")}
chars = {x["id"]: x for x in R("cb8af508-characters-export.2026-11-26T16_26_22.62200_00.csv")}
links = R("73620129-instant_story_characters-export.2026-11-26T16_26_49.17200_00.csv")
pages = R("a1d1e251-instant_story_pages-export.2026-11-26T16_27_43.54300_00.csv")
styles = {x["id"]: x for x in R("c8164c0e-artwork_style-export.2026-11-26T16_13_58.02900_00.csv")}
themes = {x["id"]: x for x in R("227b9512-themes-export.2026-11-26T16_28_35.73400_00.csv")}

# Real-looking names from Kyle's test-account stories -> invented names (applied to all text fields).
RENAME = [
    ("Big Daddy B", "Big Bob"), ("Great Grandson", "grandson"), ("Great-Grandson", "grandson"),
    ("Freya", "Isla"), ("Reuben", "Theo"), ("Noah", "Finn"), ("Reggie", "Biscuit"),
    ("GG", "Grandpa Bert"), ("Wilmslow", "Willowbrook"), ("Doris", "Dot"),
    (" from Manchester, England", ""), ("Manchester", "the city"),
]

def rename(s):
    for a, b in RENAME:
        s = re.sub(rf"\b{re.escape(a)}\b", b, s) if a[0].isalnum() else s.replace(a, b)
    return s

def J(s):
    try:
        v = json.loads(s) if s else {}
        return v if isinstance(v, dict) else {}
    except json.JSONDecodeError:
        return {}

# Attribute fills for characters whose JSON is empty. Marked "assigned" in the output so the
# judge knows these came from the golden-set author, not the original user.
