def char_record(cid):
    c = chars[cid]
    rec = {"source_character_id": int(cid), "name": rename(c["name"]),
           "physical_description": rename(c["physical_description"])}
    assigned = []
    for k in ["primary_attributes", "face_attributes", "eyes_attributes", "hair_attributes", "clothing_attributes"]:
        v = J(c[k])
        f = FILL.get(cid, {}).get(k)
        if f:
            v = {**v, **{kk: vv for kk, vv in f.items() if vv or not v.get(kk)}}
            assigned.append(k)
        rec[k] = {kk: (rename(vv) if isinstance(vv, str) else vv) for kk, vv in v.items()}
    if assigned:
        rec["assigned_by_golden_set"] = assigned
    return rec

def style_rec(sid):
    s = styles[sid]
    return {"id": int(sid), "name": s["name"], "plan_level": int(s["plan_level"]), "description": s["description"],
            "image_prompt_positive": s["image_prompt_positive"], "image_prompt_negative": s["image_prompt_negative"]}

def theme_rec(tid):
    t = themes[tid]
    return {"id": int(tid), "name": t["name"], "image_keywords": t["image_keywords"]}

out = []
for gid, sid, tests in SELECTION:
    s = stories[sid]
    cids = []
    for l in links:
        if l["instant_stories_id"] == sid and l["characters_id"] not in cids and l["characters_id"] not in DROP_CHARS:
            cids.append(l["characters_id"])
    ps = sorted([p for p in pages if p["instant_stories_id"] == sid], key=lambda p: int(p["page_number"]))
    out.append({
        "golden_id": gid, "source": {"instant_stories_id": int(sid), "users_id": int(s["users_id"])},
        "tests": tests,
        "title": rename(s["title"]), "subtitle": rename(s["subtitle"]),
        "user_prompt": rename(s["user_prompt"]), "synopsis": rename(s["synopsis"]),
        "artwork_style": style_rec(s["artwork_style_id"]), "theme": theme_rec(s["theme_id"]),
        "characters": [char_record(c) for c in cids],
        "pages": [{"page_number": int(p["page_number"]), "text": rename(p["text"])} for p in ps],
    })

